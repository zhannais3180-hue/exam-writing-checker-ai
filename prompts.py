def build_check_prompt(task_key: str, task_text: str, student_text: str, word_count: int) -> str:
    task_rules = TASK_PROMPTS[task_key]
    return f"""
{BASE_RULES}

КОНКРЕТНОЕ ЗАДАНИЕ:
{task_rules}

УСЛОВИЕ / СТИМУЛ:
{task_text}

РАБОТА УЧЕНИКА:
{student_text}

ПОДСЧЁТ ПРОГРАММОЙ:
{word_count} слов.

Проверь работу строго по выбранным критериям и выдай результат в заданном формате.
"""
